const mongoose = require("mongoose");

const NotificationLogSchema = new mongoose.Schema(
  {
    /*
    |--------------------------------------------------------------------------
    | Module
    |--------------------------------------------------------------------------
    */

    module: {
      type: String,
      default: "GENERAL",
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Event
    |--------------------------------------------------------------------------
    */

    event: {
      type: String,
      required: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Channel
    |--------------------------------------------------------------------------
    */

    channel: {
      type: String,
      enum: ["Email", "WhatsApp", "SMS"],
      required: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Recipient
    |--------------------------------------------------------------------------
    */

    recipient: {
      type: String,
      required: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Subject
    |--------------------------------------------------------------------------
    */

    subject: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | Message
    |--------------------------------------------------------------------------
    */

    message: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | Payload
    |--------------------------------------------------------------------------
    */

    payload: {
      type: mongoose.Schema.Types.Mixed,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Provider
    |--------------------------------------------------------------------------
    */

    provider: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | Message ID
    |--------------------------------------------------------------------------
    */

    messageId: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | Status
    |--------------------------------------------------------------------------
    */

    status: {
      type: String,
      enum: ["Pending", "Sent", "Failed"],
      default: "Pending",
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Provider Response
    |--------------------------------------------------------------------------
    */

    response: {
      type: mongoose.Schema.Types.Mixed,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Error Message
    |--------------------------------------------------------------------------
    */

    errorMessage: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | Retry Count
    |--------------------------------------------------------------------------
    */

    retryCount: {
      type: Number,
      default: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Sent At
    |--------------------------------------------------------------------------
    */

    sentAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
  },
);

module.exports = mongoose.model("NotificationLog", NotificationLogSchema);
